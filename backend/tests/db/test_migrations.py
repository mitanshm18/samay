"""Migration 0001: round trip, no drift from the models, and the schema rules."""

from __future__ import annotations

import pytest
from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected
from dbhelpers import alembic_config, example, migrate
from sqlalchemy import Engine, create_engine, inspect, text
from sqlalchemy.engine import URL

from samay.db import save_bill
from samay.db.models import Base

TABLES = {"bill_document", "calculation_run"}
MONEY_COLUMNS = {"calculated_total_paise", "printed_total_paise", "total_difference_paise"}


def _tables(url: URL) -> set[str]:
    engine = create_engine(url)
    try:
        return set(inspect(engine).get_table_names()) - {"alembic_version"}
    finally:
        engine.dispose()


def test_upgrade_downgrade_upgrade(empty_url: URL) -> None:
    migrate(empty_url)
    assert _tables(empty_url) == TABLES
    migrate(empty_url, "base", down=True)
    assert _tables(empty_url) == set()
    migrate(empty_url)
    assert _tables(empty_url) == TABLES


def test_models_match_the_migration(db: Engine) -> None:
    with db.begin() as connection:
        config = alembic_config()
        config.attributes["connection"] = connection
        command.check(config)  # raises AutogenerateDiffsDetected on any drift


def test_drift_is_detected(db: Engine) -> None:
    """The check above can fail: an extra column in the database is drift."""
    with db.begin() as connection:
        connection.execute(text("ALTER TABLE bill_document ADD COLUMN stray TEXT"))
        config = alembic_config()
        config.attributes["connection"] = connection
        with pytest.raises(AutogenerateDiffsDetected):
            command.check(config)


def test_no_float_or_numeric_column_anywhere(db: Engine) -> None:
    with db.connect() as connection:
        rows = connection.execute(
            text(
                "SELECT table_name, column_name, data_type FROM information_schema.columns"
                " WHERE table_schema = 'public'"
            )
        ).all()
    assert rows
    forbidden = {"real", "double precision", "numeric", "money"}
    assert [r for r in rows if r.data_type in forbidden] == []
    money = {r.column_name: r.data_type for r in rows if r.column_name in MONEY_COLUMNS}
    assert money == dict.fromkeys(MONEY_COLUMNS, "bigint")


def test_money_columns_have_no_default(db: Engine) -> None:
    """Missing is never zero: nothing fills a money column in by default."""
    columns = inspect(db).get_columns("calculation_run")
    for column in columns:
        if column["name"] in MONEY_COLUMNS:
            assert column["nullable"] is True
            assert column["default"] is None


def test_immutability_triggers_exist(db: Engine) -> None:
    with db.connect() as connection:
        names = set(
            connection.execute(
                text("SELECT tgname FROM pg_trigger WHERE NOT tgisinternal")
            ).scalars()
        )
    assert names == {f"{t}_immutable" for t in TABLES} | {f"{t}_no_truncate" for t in TABLES}


def test_models_declare_every_table() -> None:
    assert set(Base.metadata.tables) == TABLES


def test_downgrade_refuses_while_records_exist(db: Engine) -> None:
    save_bill(db, example("matching.json"))
    with db.begin() as connection:
        config = alembic_config()
        config.attributes["connection"] = connection
        with pytest.raises(RuntimeError, match="refusing to downgrade"):
            command.downgrade(config, "base")
    assert set(inspect(db).get_table_names()) >= TABLES
